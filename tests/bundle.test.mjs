/**
 * The built browser bundle must register itself in the shape the dsh web shell
 * reads: one `window.__ModuleLoader__.load({ id, factory })` call whose factory
 * receives `require` for the platform module table.
 *
 * The factory itself is not executed here — it needs the page's module table —
 * so this checks the handoff, the declared externals, and that every external
 * is one the platform actually seeds.
 */

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { test } from 'node:test'

/** Module table seeded by the web shell (`packages/client/web/src/platform.ts`). */
const PLATFORM_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

const source = readFileSync(resolve(import.meta.dirname, '../lib/client.js'), 'utf8')

test('the client bundle registers one factory under the package id', () => {
  let registered
  const window = { __ModuleLoader__: { load: (registration) => { registered = registration } } }
  // The bundle is a script, not a module: it registers through the window global.
  new Function('window', source)(window)
  assert.ok(registered, 'the bundle called window.__ModuleLoader__.load')
  assert.equal(registered.id, 'dsh-shell-switch')
  assert.equal(typeof registered.factory, 'function')
})

test('the client bundle requires only platform modules', () => {
  const required = [...new Set([...source.matchAll(/require\("([^"]+)"\)/gu)].map(match => match[1]))]
  assert.ok(required.length > 0, 'the bundle requires its externals')
  for (const specifier of required) {
    assert.ok(PLATFORM_MODULES.includes(specifier), `${specifier} is not seeded by the platform module table`)
  }
})

test('the host bundle is an ESM module that leaves the harness packages external', () => {
  const host = readFileSync(resolve(import.meta.dirname, '../lib/index.js'), 'utf8')
  assert.match(host, /^\/\/ Generated by scripts\/build\.mjs/u)
  const imported = [...new Set([...host.matchAll(/from\s+"([^"]+)"/gu)].map(match => match[1]))]
  for (const specifier of imported) {
    assert.ok(specifier.startsWith('@deepseek-ai/') || specifier.startsWith('node:'), `unexpected host import ${specifier}`)
  }
})
